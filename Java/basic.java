//What is bytecode in Java, and why does Java generate bytecode instead of directly generating machine code?

//Bytecode is an intermediate, platform-independent representation of Java source code generated by the Java compiler and stored in a .class file. Java generates bytecode instead of directly generating machine code to achieve platform independence. The JVM executes this bytecode on different operating systems, following the Write Once, Run Anywhere principle."

//Typecasting
//there are two type of type conversion
//Widening(smaller data type to larger) & Narrowing(larger to smaller)
class basic{
    public static void main(String[] args){
        int a=10;
        double b=a; //widening
        System.out.println(b);

        double x=10.5;
        int y=(int)x;//narrowing
        System.out.println(y);
    }
}


